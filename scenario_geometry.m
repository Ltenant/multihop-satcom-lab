%% Визуализация геометрии многоскачкового спутникового сценария
% Строит 3D-снимок satelliteScenario: центр Земли, два спутника, их орбиты
% и межспутниковая линия. Положения получаются функцией states(), орбиты
% восстанавливаются из кеплеровых элементов, которыми создавались спутники.
% Работает без интерактивного Satellite Scenario Viewer, поэтому рисунок
% можно экспортировать в файл изображения.
%
% Предусловие: в рабочей области есть сценарий satelliteScenario с двумя
% спутниками (переменные sc, sat1, sat2).

% --- Папка вывода для экспортируемого изображения ---
outDir = pwd;

% --- 1. Момент времени: любой внутри окна видимости ---
t = sc.StartTime + minutes(75);

% --- 2. Положения спутников в инерциальной системе координат ---
% states(sat, t) возвращает 3x1 вектор координат [x; y; z] в ICRF, м
p1 = states(sat1, t);                    % положение спутника 1
p2 = states(sat2, t);                    % положение спутника 2

% --- 3. Фигура (невидимая — экспорт в файл без экрана) ---
fig = figure("Visible","off","Color","w");
hold on;

% Центр Земли
plot3(0,0,0,'yo','MarkerSize',12,'MarkerFaceColor','y');
% Положения спутников в момент t
plot3(p1(1),p1(2),p1(3),'bo','MarkerSize',10,'MarkerFaceColor','b');
plot3(p2(1),p2(2),p2(3),'rs','MarkerSize',10,'MarkerFaceColor','r');
% Межспутниковая линия Sat1 -> Sat2
plot3([p1(1) p2(1)],[p1(2) p2(2)],[p1(3) p2(3)],'k-','LineWidth',2);

% --- 4. Орбиты восстанавливаю аналитически из кеплеровых элементов ---
th = linspace(0,2*pi,200);               % параметр обхода орбиты
r = 1e7;                                 % радиус орбиты, м (a = 10 000 км)

% Орбита 1: i = 0°, RAAN = 0° — лежит в плоскости экватора
plot3(r*cos(th), r*sin(th), zeros(size(th)), 'b:');

% Орбита 2: i = 30°, RAAN = 120°
i2    = 30*pi/180;                       % наклонение, рад
raan2 = 120*pi/180;                      % долгота восходящего узла, рад
% Матрица поворота: наклон плоскости орбиты вокруг X, затем поворот
% на RAAN вокруг Z
R = [cos(raan2) -sin(raan2) 0;
     sin(raan2)  cos(raan2) 0;
     0           0          1] * ...
    [1 0        0;
     0 cos(i2) -sin(i2);
     0 sin(i2)  cos(i2)];
orb2 = R*[r*cos(th); r*sin(th); zeros(size(th))];
plot3(orb2(1,:), orb2(2,:), orb2(3,:), 'r:');

% --- 5. Оформление и экспорт в PNG ---
axis equal; grid on;
xlabel('X, м'); ylabel('Y, м'); zlabel('Z, м');
title('Геометрия сценария: межспутниковая линия');
view(45,25);
exportgraphics(fig, fullfile(outDir,'scenario_geometry.png'), 'Resolution',150);
